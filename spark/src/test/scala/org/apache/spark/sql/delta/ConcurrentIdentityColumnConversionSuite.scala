    withTable("target") {
      createLegacyTableWithCicWithoutSequenceId(rows = Seq(10, 20, 30))
      val maxBefore = selectMaxId

      spark.sql(cicDropFeatureDdl)

      val snapshot = deltaLog.update()
      assert(!snapshot.protocol.isFeatureSupported(ConcurrentIdentityColumnsTableFeature),
        "DROP FEATURE must remove the CIC feature from the protocol.")

      spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (40), (50)")
      assert(selectMaxId > maxBefore,
        s"Post-downgrade stock values must continue past $maxBefore, got $selectMaxId.")
      assertCorrectIdentityColumn(readDeltaTable(tempPath).select("ids"), expectedSize = 5L)
    }
  }

  test("DROP FEATURE then re-convert round-trips a table with multiple CIC columns") {
    // Coverage for the multi-column + re-conversion gap: the conversion/downgrade tests elsewhere
    // are single-column and never chained. Drive a TWO-identity-column table CIC -> v1 (DROP
    // FEATURE) -> CIC (re-opt-in), asserting both columns are stamped, stripped, and re-stamped
    // together (whole-table) and that each column's values keep advancing across every transition.
    def pointer(col: String): Option[String] =
      ConcurrentIdentityColumnSchema.getSequenceId(deltaLog.update().metadata.schema(col))
    def maxOf(col: String): Long =
      spark.sql(s"SELECT max($col) AS m FROM delta.`$tempPath`").head().getLong(0)

    withTable("target") {
      // 1. CIC table with two identity columns: CREATE under the feature stamps both.
      withSQLConf(DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true") {
        spark.sql(createTargetTableStatement(Seq(
          "idA BIGINT GENERATED ALWAYS AS IDENTITY",
          "idB BIGINT GENERATED ALWAYS AS IDENTITY",
          "values INT")))
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (10), (20), (30)")
      }
      assert(pointer("idA").isDefined && pointer("idB").isDefined,
        "CREATE under the CIC feature must stamp every identity column.")
      val (aCic, bCic) = (maxOf("idA"), maxOf("idB"))

      // 2. DROP FEATURE -> v1: strip every pointer, drop the feature, write each column's HWM.
      spark.sql(cicDropFeatureDdl)
      val snap = deltaLog.update()
      assert(!snap.protocol.isFeatureSupported(ConcurrentIdentityColumnsTableFeature),
        "DROP FEATURE must remove the CIC feature.")
      assert(pointer("idA").isEmpty && pointer("idB").isEmpty,
        "DROP FEATURE must strip the pointer from every identity column.")
      spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (40), (50)")
      assert(maxOf("idA") > aCic && maxOf("idB") > bCic,
        "Post-downgrade stock values must continue past the CIC max for both columns.")
      val (aV1, bV1) = (maxOf("idA"), maxOf("idB"))

      // 3. Re-opt-in -> CIC again: a fresh sequence per column, seeded past the v1 data.
      val createsBefore = localService.createSequenceCount
      spark.sql(cicFeatureOptInDdl)
      assert(localService.createSequenceCount === createsBefore + 2,
        "Re-conversion must mint one fresh sequence for each of the two identity columns.")
      assert(pointer("idA").isDefined && pointer("idB").isDefined,
        "Re-conversion must re-stamp every identity column.")
      withSQLConf(DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true") {
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (60), (70)")
      }
      assert(maxOf("idA") > aV1 && maxOf("idB") > bV1,
        "Post-re-conversion service values must continue past the v1 max for both columns.")

      // Every value of each identity column is distinct across the full round-trip.
      assertCorrectIdentityColumn(readDeltaTable(tempPath).select("idA"), expectedSize = 7L)
      assertCorrectIdentityColumn(readDeltaTable(tempPath).select("idB"), expectedSize = 7L)
    }
  }

  test("DROP FEATURE migrates the service high-water mark, not the table max/min") {
    // The local HWM should be converted to a sequence HWM and vice versa. Extreme values should
    // be ignored during this conversion. Only SYNC should take them into account.
    // For this reason this test uses GENERATED BY DEFAULT and populates which lets us insert an
    // explicit id far ABOVE the HWM. The HWM must stay BELOW the explicit data max for the two
    // migration sources to be distinguishable.

    val step = 2L
    val start = 1L
    // Force a single large reserve so the service HWM is deterministic. The 3-row insert draws
    // fewer than `reserveSize` values, so the buffer never drains: exactly one UC reserve of
    // `reserveSize` fires (no adaptive doubling, no prefetch), leaving the service's next value at
    // `start + reserveSize * step`.
    val reserveSize = 64L
    // The service HWM the downgrade must migrate: the next value the service would have minted,
    // strictly past every service-minted id and far below the explicit data max.
    val serviceHwm = start + reserveSize * step
    // The explicit id sits a full reserve-window (`reserveSize * 1024`) above the seeded range, so
    // it can never accidentally collide with a service-reserved value.
    val explicitId = serviceHwm * 1024L
    // Stock v1 continues at base = HWM + step; this also becomes the new schema HWM.
    val v1Value = serviceHwm + step
    // Re-conversion seeds the fresh sequence from schema HWM + step; this is the next service id.
    val reconvertedValue = v1Value + step
    withTable("target") {
      withSQLConf(
          DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true",
          DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_RESERVE_DRIVER_INITIAL_SIZE.key ->
            reserveSize.toString) {
        spark.sql(createTargetTableStatement(Seq(
          s"ids BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH $start INCREMENT BY $step)",
          "values INT")))
        // Service-minted rows: advance the service HWM to `serviceHwm` (a small value).
        val reservesBeforeInsert = localService.reserveIdsCount
        val reserveSizesBeforeInsert = localService.reserveRequestSizes.size
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (1), (2), (3)")
        // The large reserveSize guarantees exactly one UC reserve.
        assert(localService.reserveIdsCount === reservesBeforeInsert + 1L,
          s"Setup: the insert must trigger exactly one service reserve; got " +
            s"${localService.reserveIdsCount - reservesBeforeInsert}.")
        assert(localService.reserveRequestSizes.drop(reserveSizesBeforeInsert) === Seq(reserveSize),
          s"Setup: the single reserve must request exactly reserveSize=$reserveSize values, got " +
            s"${localService.reserveRequestSizes.drop(reserveSizesBeforeInsert)}.")
        // Explicit id far above the HWM (BY DEFAULT permits it). Touches no service, feeds no HWM.
        spark.sql(s"INSERT INTO delta.`$tempPath` (ids, values) VALUES ($explicitId, 99)")
      }
      assert(syncedSequenceId.isDefined, "Setup: a conf-on table must carry a sequenceId.")
      assert(selectMaxId === explicitId,
        s"Setup: the explicit id $explicitId must be the table max, got $selectMaxId.")
      assert(selectMaxId > serviceHwm,
        s"Setup: the table max $selectMaxId must sit far above the service HWM $serviceHwm so " +
          "the two migration sources are distinguishable.")

      // 1. DROP FEATURE -> v1: the downgrade migrates the SERVICE HWM, not the data max.
      spark.sql(cicDropFeatureDdl)
      assert(syncedSequenceId.isEmpty, "The pre-downgrade must strip the sequence pointer.")
      // Stock v1 generation continues from the migrated HWM (base = HWM + step), so a new
      // auto-generated id is serviceHwm + step -- well below the explicit data max. Had the
      // downgrade migrated the DATA max instead, this would be explicitId-derived (4097+).
      spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (100)")
      val newAutoId = readDeltaTable(tempPath).where("values = 100").select("ids").head().getLong(0)
      assert(newAutoId === v1Value,
        s"Post-downgrade auto id must continue from the SERVICE HWM (serviceHwm + step = " +
          s"$v1Value), got $newAutoId. A value >= $explicitId means the downgrade migrated the " +
          "table max instead of the service high-water mark (BUG).")
      assert(newAutoId < explicitId,
        s"Post-downgrade auto id $newAutoId must be strictly below the explicit data max " +
          s"$explicitId (else the downgrade scanned the data).")

      // 2. Re-opt-in -> CIC again: re-conversion is HWM-driven too, NOT a data scan. It mints one
      // fresh sequence seeded from the schema HWM (now `v1Value` from the stock write above), so
      // the next service id continues from there -- again below the explicit data max.
      val createsBeforeReconvert = localService.createSequenceCount
      spark.sql(cicFeatureOptInDdl)
      assert(localService.createSequenceCount === createsBeforeReconvert + 1,
        "Re-conversion must mint exactly one fresh sequence for the one identity column.")
      assert(syncedSequenceId.isDefined, "Re-conversion must re-stamp the sequence pointer.")
      withSQLConf(
          DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true",
          DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_RESERVE_DRIVER_INITIAL_SIZE.key ->
            reserveSize.toString) {
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (200)")
      }
      val cicAutoId = readDeltaTable(tempPath).where("values = 200").select("ids").head().getLong(0)
      assert(cicAutoId === reconvertedValue,
        s"Post-re-conversion service id must continue from the schema HWM (HWM + step = " +
          s"$reconvertedValue), got $cicAutoId. A value >= $explicitId means re-conversion " +
          "seeded from the data max instead of the high-water mark (BUG).")
      assert(cicAutoId < explicitId,
        s"Post-re-conversion service id $cicAutoId must be strictly below the explicit data max " +
          s"$explicitId (else re-conversion scanned the data).")

      // The explicit value survives the full CIC -> v1 -> CIC round-trip untouched, and no
      // generated id ever collided with it.
      assert(selectMaxId === explicitId,
        s"The explicit data max $explicitId must survive the round-trip untouched, " +
          s"got $selectMaxId.")
      assertCorrectIdentityColumn(readDeltaTable(tempPath).select("ids"), expectedSize = 6L)
    }
  }

  private val dropWithoutServiceConf =
    DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_DROP_WITHOUT_SERVICE.key

  test("DROP FEATURE without the service migrates the table max/min, not the service HWM") {
    // Mirror of "DROP FEATURE migrates the service high-water mark, not the table max/min":
    // with the escape-hatch conf on, the downgrade scans the data extreme (like SYNC) instead of
    // reserving from the service, so the migrated HWM is the DATA max, and neither reserveIds nor
    // dropSequence is called. GENERATED BY DEFAULT lets us insert an explicit id far above the
    // service HWM so the two migration sources are distinguishable.
    val step = 2L
    val start = 1L
    val reserveSize = 64L
    val serviceHwm = start + reserveSize * step
    // On the lattice (start=1, step=2 -> odd) so the scanned mark needs no rounding.
    val explicitId = serviceHwm * 1024L + 1L
    // The data max is the explicit id; stock v1 continues at dataMax + step.
    val v1Value = explicitId + step
    withTable("target") {
      withSQLConf(
          DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true",
          DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_RESERVE_DRIVER_INITIAL_SIZE.key ->
            reserveSize.toString) {
        spark.sql(createTargetTableStatement(Seq(
          s"ids BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH $start INCREMENT BY $step)",
          "values INT")))
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (1), (2), (3)")
        // Explicit id far above the service HWM (BY DEFAULT permits it). Touches no service.
        spark.sql(s"INSERT INTO delta.`$tempPath` (ids, values) VALUES ($explicitId, 99)")
      }
      assert(syncedSequenceId.isDefined, "Setup: a conf-on table must carry a sequenceId.")
      val droppedSequenceId = syncedSequenceId.get
      val serviceTableId =
        ConcurrentIdentityColumnSchema.sequenceServiceTableId(deltaLog.update().metadata)
      assert(selectMaxId === explicitId,
        s"Setup: the explicit id $explicitId must be the table max, got $selectMaxId.")
      assert(selectMaxId > serviceHwm,
        s"Setup: the table max $selectMaxId must sit above the service HWM $serviceHwm so the " +
          "two migration sources are distinguishable.")

      // DROP FEATURE with the escape hatch on: the downgrade scans the data, never the service.
      val reservesBefore = localService.reserveIdsCount
      val dropsBefore = localService.dropSequenceCount
      withSQLConf(dropWithoutServiceConf -> "true") {
        spark.sql(cicDropFeatureDdl)
      }
      assert(!deltaLog.update().protocol.isFeatureSupported(ConcurrentIdentityColumnsTableFeature),
        "DROP FEATURE must remove the CIC feature from the protocol.")
      assert(syncedSequenceId.isEmpty, "The pre-downgrade must strip the sequence pointer.")
      assert(localService.reserveIdsCount === reservesBefore,
        "The escape hatch must NOT reserve from the service during downgrade.")
      assert(localService.dropSequenceCount === dropsBefore,
        "The escape hatch must NOT drop the service sequence (it is left to service GC).")
      assert(localService.hasSequence(serviceTableId, droppedSequenceId),
        "The escape hatch leaves the orphaned sequence in the service (no dropSequence).")

      // Stock v1 continues from the migrated DATA max (dataMax + step), not the service HWM.
      spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (100)")
      val newAutoId = readDeltaTable(tempPath).where("values = 100").select("ids").head().getLong(0)
      assert(newAutoId === v1Value,
        s"Post-downgrade auto id must continue from the DATA max (explicitId + step = $v1Value), " +
          s"got $newAutoId. A value near ${serviceHwm + step} means the downgrade migrated the " +
          "service high-water mark instead of scanning the data (BUG).")
      assertCorrectIdentityColumn(readDeltaTable(tempPath).select("ids"), expectedSize = 5L)
    }
  }

  test("DROP FEATURE without the service succeeds even when the sequence is gone") {
    // The whole point of the escape hatch: leave the feature while the service is unavailable.
    // Simulate that by dropping the sequence out from under the table first, then downgrade with
    // the conf on. The default (service) path would fail trying to reserve from the missing
    // sequence; the escape hatch scans the data and succeeds.
    withTable("target") {
      withSQLConf(DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true") {
        spark.sql(createTargetTableStatement(Seq(
          "ids BIGINT GENERATED ALWAYS AS IDENTITY",
          "values INT")))
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (10), (20), (30)")
      }
      assert(syncedSequenceId.isDefined, "Setup: a conf-on table must carry a sequenceId.")
      val sequenceId = syncedSequenceId.get
      val serviceTableId =
        ConcurrentIdentityColumnSchema.sequenceServiceTableId(deltaLog.update().metadata)
      val maxBefore = selectMaxId
      // Retire the sequence behind the table's back: the service can no longer serve it.
      localService.dropSequence(DropSequenceRequest(sequenceId, serviceTableId))
