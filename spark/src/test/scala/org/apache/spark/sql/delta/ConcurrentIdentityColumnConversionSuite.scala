  private def cicDropFeatureDdl: String =
    s"ALTER TABLE delta.`$tempPath` DROP FEATURE " +
      s"`${ConcurrentIdentityColumnsTableFeature.name}`"

  test("DROP FEATURE returns a service-backed table to stock identity") {
    // Leaving the service backend is table-level DDL: the pre-downgrade hook computes the
    // stock schema high-water mark from the data, strips the sequence pointer, and the
    // command drops the feature. A subsequent stock-identity INSERT continues past the
    // service-written data instead of restarting from `start`.
    withTable("target") {
      withSQLConf(DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true") {
        spark.sql(createTargetTableStatement(Seq(
          "ids BIGINT GENERATED ALWAYS AS IDENTITY",
          "values INT")))
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (10), (20), (30)")
      }
      assert(syncedSequenceId.isDefined, "Setup: a conf-on table must carry a sequenceId.")
      val droppedSequenceId = syncedSequenceId.get
      val serviceTableId =
        ConcurrentIdentityColumnSchema.sequenceServiceTableId(deltaLog.update().metadata)
      assert(localService.hasSequence(serviceTableId, droppedSequenceId),
        "Setup: the service sequence must exist before DROP FEATURE.")
      val dropsBefore = localService.dropSequenceCount
      val maxBefore = selectMaxId

      spark.sql(cicDropFeatureDdl)

      val snapshot = deltaLog.update()
      assert(!snapshot.protocol.isFeatureSupported(ConcurrentIdentityColumnsTableFeature),
        "DROP FEATURE must remove the CIC feature from the protocol.")
      assert(syncedSequenceId.isEmpty,
        "The pre-downgrade must strip the sequence pointer.")
      assert(localService.dropSequenceCount === dropsBefore + 1,
        "DROP FEATURE must retire the service sequence (one dropSequence call).")
      assert(!localService.hasSequence(serviceTableId, droppedSequenceId),
        "DROP FEATURE must drop the service sequence rather than orphan it.")

      // Stock identity (no CIC feature, conf off) reads the schema HWM the downgrade wrote.
      spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (40), (50)")
      assert(selectMaxId > maxBefore,
        s"Post-downgrade stock values must continue past $maxBefore, got $selectMaxId.")
      assertCorrectIdentityColumn(readDeltaTable(tempPath).select("ids"), expectedSize = 5L)
    }
  }

  test("DROP FEATURE on an unconverted feature-on table returns it to stock identity") {
    // A legacy table (feature on, never stamped) can leave directly: the pre-downgrade syncs
    // its columns' schema HWMs from the data (it has no pointer to strip), so stock identity
