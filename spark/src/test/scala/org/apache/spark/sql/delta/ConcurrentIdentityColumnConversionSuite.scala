/**
 * Verifies the table-level CIC conversion and downgrade DDL on the service backend:
 *
 *   - SYNC IDENTITY reconciles / repairs an existing service sequence.
 *   - CIC feature opt-in (ALTER ... SET TBLPROPERTIES) converts a stock identity table.
 *   - DROP FEATURE returns a service-backed table to stock identity.
 *   - The `identityColumn.concurrent.enabled` kill switch blocks conversion / repair while
 *     leaving the DROP FEATURE escape hatch working.
 *
 * Re-uses the suite scaffolding from [[ConcurrentIdentityColumnSuiteBase]] (table
 * properties enabling the CIC feature, MERGE helpers) and the same
 * [[SharedLocalIdentitySequenceService]] backend injection documented on
 * [[ConcurrentIdentityColumnServiceBackendSuite]].
 *
 * The phase-locking mixins ([[TransactionExecutionTestMixin]], [[PhaseLockingTestMixin]]) back the
 * two SYNC-vs-write race tests, which hold a transaction at pre-commit while a conflicting one
 * commits. Note that the tests still run sequentially.
 */
class ConcurrentIdentityColumnConversionSuite extends ConcurrentIdentityColumnSuiteBase
  with TransactionExecutionTestMixin
  with PhaseLockingTestMixin {

  import testImplicits._

  private def selectMaxId: Long =
    spark.sql(s"SELECT max(ids) AS m FROM delta.`$tempPath`").head().getLong(0)

  private def syncedSequenceId: Option[String] =
    ConcurrentIdentityColumnSchema.getSequenceId(deltaLog.update().metadata.schema("ids"))

  /**
   * Fabricates an unconverted LEGACY table: a plain identity table whose protocol carries
   * the CIC feature but whose columns have no sequence pointer, optionally with rows
   * written through the stock identity path. This is unconverted on-disk shape; it can no
   * longer be produced through DDL (CREATE stamps on feature opt-in and ALTER converts), so
   * the protocol upgrade is committed raw, deliberately bypassing the conversion hook.
   */
  private def createLegacyTableWithCicWithoutSequenceId(rows: Seq[Int] = Nil): Unit = {
    spark.sql(
      s"""CREATE TABLE target (
         |  ids BIGINT GENERATED ALWAYS AS IDENTITY,
         |  values INT)
         |USING DELTA
         |LOCATION '$tempPath'
         |tblproperties(
         |  ${TableFeatureProtocolUtils.propertyKey(IdentityColumnsTableFeature)} = 'enabled')
         |""".stripMargin)
    if (rows.nonEmpty) {
      // Stock identity writes (the CIC feature is not on the protocol yet).
      spark.sql(
        s"INSERT INTO delta.`$tempPath` (values) VALUES ${rows.map(v => s"($v)").mkString(", ")}")
    }
    val txn = deltaLog.startTransaction()
    txn.updateProtocol(txn.protocol.merge(
      Protocol.forTableFeature(ConcurrentIdentityColumnsTableFeature)))
    txn.commit(Nil, DeltaOperations.ManualUpdate)
    assert(deltaLog.update().protocol.isFeatureSupported(ConcurrentIdentityColumnsTableFeature),
      "Legacy fixture: the raw protocol upgrade must land the CIC feature.")
    assert(syncedSequenceId.isEmpty,
      "Legacy fixture: the raw upgrade must NOT stamp a sequence pointer.")
  }

  test("SYNC IDENTITY reconciles the service sequence and mints a fresh id (service backend)") {
    // GENERATED BY DEFAULT lets us insert explicit values the service never saw. After SYNC the
    // service must be reseeded past them (minting a NEW sequence id) so the next auto value clears
    // the explicit max instead of colliding from the original start.
    withTable("target") {
      withSQLConf(DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true") {
        spark.sql(createTargetTableStatement(Seq(
          "ids BIGINT GENERATED BY DEFAULT AS IDENTITY",
          "values INT")))
        spark.sql(s"INSERT INTO delta.`$tempPath` (ids, values) VALUES (100, 1), (200, 2)")

        val seqBefore = syncedSequenceId.get
        val numCreatesBefore = localService.createSequenceCount
        val serviceTableId =
          ConcurrentIdentityColumnSchema.sequenceServiceTableId(deltaLog.update().metadata)
        val dropsBefore = localService.dropSequenceCount
        spark.sql(s"ALTER TABLE delta.`$tempPath` ALTER COLUMN ids SYNC IDENTITY")

        assert(syncedSequenceId.get != seqBefore, "SYNC must mint a fresh sequence id.")
        assert(localService.createSequenceCount === numCreatesBefore + 1,
          "SYNC must create exactly one new sequence.")
        assert(localService.dropSequenceCount === dropsBefore + 1,
          "SYNC must retire the superseded sequence (one dropSequence call).")
        assert(!localService.hasSequence(serviceTableId, seqBefore),
          "SYNC must drop the old sequence rather than orphan it.")

        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (3)")
        val autoId = readDeltaTable(tempPath).where("values = 3").select("ids").head().getLong(0)
        assert(autoId > 200L, s"Post-SYNC auto value must clear the explicit max 200, got $autoId.")
        assertCorrectIdentityColumn(readDeltaTable(tempPath).select("ids"), expectedSize = 3L)
      }
    }
  }

