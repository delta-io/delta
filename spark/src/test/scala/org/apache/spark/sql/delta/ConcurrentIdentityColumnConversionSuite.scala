  /**
   * Collect the CIC usage events of one `opType` emitted while running `f`, as parsed blobs.
   * The dashboard reads these opType strings and blob keys, so asserting on them here is what
   * keeps a rename from silently breaking a panel.
   */
  private def cicEvents(opType: String)(f: => Unit): Seq[Map[String, Any]] =
    Log4jUsageLogger.track(f)
      .filter { e =>
        e.metric == MetricDefinitions.EVENT_TAHOE.name && e.tags.get("opType").contains(opType)
      }
      .map(e => JsonUtils.fromJson[Map[String, Any]](e.blob))

  test("dropSequence event: DROP COLUMN reports its own retirement path") {
    withTable("target") {
      withSQLConf(
        DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true",
        DeltaSQLConf.DELTA_ALTER_TABLE_DROP_COLUMN_ENABLED.key -> "true") {
        spark.sql(createTargetTableStatement(Seq(
          "ids BIGINT GENERATED ALWAYS AS IDENTITY",
          "values INT")))
        spark.sql(
          s"ALTER TABLE delta.`$tempPath` SET TBLPROPERTIES ('delta.columnMapping.mode' = 'name')")
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (1)")

        val events = cicEvents(ConcurrentIdentityColumnObservability.opTypeDropSequence) {
          spark.sql(s"ALTER TABLE delta.`$tempPath` DROP COLUMN ids")
        }

        assert(events.size === 1, s"Expected exactly one dropSequence event, got $events.")
        assert(events.head("reason") ===
          ConcurrentIdentityColumnObservability.DropReason.DropColumn)
      }
    }
  }

