  test("SYNC IDENTITY refuses an unconverted legacy table") {
    // SYNC is repair-only: it reseeds an EXISTING service sequence. A legacy table (CIC
    // feature on, no sequence pointer) is unconverted state, and converting is the conversion
    // DDL's concern, not SYNC's. SYNC must refuse with the missing-stamp error and leave the
    // state untouched.
    withTable("target") {
      createLegacyTableWithCicWithoutSequenceId(rows = Seq(10, 20, 30))
      val numCreatesBefore = localService.createSequenceCount

      val cause = cicReservationCause(intercept[Exception] {
        spark.sql(s"ALTER TABLE delta.`$tempPath` ALTER COLUMN ids SYNC IDENTITY")
      })
      checkError(
        cause,
        condition = "DELTA_CONCURRENT_IDENTITY_COLUMN_CONVERSION_INCOMPLETE",
        sqlState = "XXKDS",
        parameters = cause.getMessageParameters.asScala.toMap)
      assert(localService.createSequenceCount === numCreatesBefore,
        "A refused SYNC must not create a sequence.")
      assert(syncedSequenceId.isEmpty, "A refused SYNC must not stamp a sequenceId.")
    }
  }

  test("SYNC IDENTITY repairs independently of the session conf") {
    // SYNC no longer routes on CONCURRENT_IDENTITY_COLUMN_ENABLED: on a stamped table it is
    // always the service repair (the old conf-off downgrade flow is gone; leaving the service
    // backend is table-level DDL). Run SYNC with the conf at its default (off) and verify it
    // still re-mints a fresh sequence and keeps the stamp.
    withTable("target") {
      withSQLConf(DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true") {
        spark.sql(createTargetTableStatement(Seq(
          "ids BIGINT GENERATED ALWAYS AS IDENTITY",
          "values INT")))
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (10), (20), (30)")
      }
      assert(syncedSequenceId.isDefined, "Setup: a conf-on table must carry a sequenceId.")
      val seqBefore = syncedSequenceId.get
      val numCreatesBefore = localService.createSequenceCount

      // Conf at its default (off): SYNC must still repair, not downgrade.
      spark.sql(s"ALTER TABLE delta.`$tempPath` ALTER COLUMN ids SYNC IDENTITY")

      assert(syncedSequenceId.isDefined, "Repair must keep the column service-backed.")
      assert(syncedSequenceId.get != seqBefore, "Repair must mint a fresh sequence id.")
      assert(localService.createSequenceCount === numCreatesBefore + 1,
        "Repair must create exactly one new sequence.")

      // The fresh sequence must be reseeded PAST the data: a write after SYNC must generate ids
      // beyond the existing max, proving the effective high-water mark advanced.
      val maxBefore = selectMaxId
      withSQLConf(DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true") {
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (40)")
      }
      assert(selectMaxId > maxBefore,
        s"Post-SYNC values must clear the pre-SYNC max $maxBefore, got $selectMaxId.")
    }
  }

  test("a service-backed write that commits after a racing SYNC IDENTITY is rejected") {
    // The central safety property of CIC SYNC: it re-stamps the sequence pointer
    // (delta.identity.concurrent.sequenceId) as a GENERIC
    // metadata change (deliberately NOT setSyncIdentity), so a concurrent write that reserved from
    // the old sequence before SYNC committed must be rejected on commit, not allowed to emit values
    // that could collide with the freshly minted sequence. Deterministic via the phase-locking
    // transaction observer: the write is held at pre-commit while SYNC commits.
    withTable("target") {
      spark.sql(createTargetTableStatement(Seq(
        "ids BIGINT GENERATED ALWAYS AS IDENTITY",
        "values INT")))
      spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (1), (2), (3)")

      val pool = ThreadUtils.newDaemonSingleThreadExecutor("cic-write-vs-sync")
      try {
        val (writeObserver, writeFuture) = runQueryWithObserver(
          name = "write",
          pool,
          s"INSERT INTO delta.`$tempPath` (values) VALUES (10), (20)")
        unblockUntilPreCommit(writeObserver)
        busyWaitFor(writeObserver.phases.preparePhase.hasEntered, timeout)

        // SYNC commits first, minting a new sequence and re-stamping the pointer.
        spark.sql(s"ALTER TABLE delta.`$tempPath` ALTER COLUMN ids SYNC IDENTITY")

        unblockCommit(writeObserver)
        val ex = intercept[Exception] {
          ThreadUtils.awaitResult(writeFuture, 30.seconds)
        }
        assert(causeChain(ex).exists(_.isInstanceOf[java.util.ConcurrentModificationException]),
          s"The racing write must fail with a Delta commit conflict; got: $ex")
      } finally {
        pool.shutdownNow()
      }

      // Interleaving-independent invariant: no duplicate identity values. The rejected write
      // committed nothing, so only the seeded rows remain.
      val ids = readDeltaTable(tempPath).select("ids")
      assert(ids.count() === ids.distinct().count(),
        "A SYNC/write race must never produce duplicate identity values.")
    }
  }

  test("a SYNC IDENTITY that commits after a racing CIC write is rejected") {
    // The other ordering: SYNC calls readWholeTable, so a write that appends rows while SYNC is in
    // flight must abort SYNC (the user re-runs it and re-scans the new data). Deterministic: SYNC
    // is held at pre-commit while the write commits.
    withTable("target") {
      spark.sql(createTargetTableStatement(Seq(
        "ids BIGINT GENERATED ALWAYS AS IDENTITY",
        "values INT")))
      spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (1), (2), (3)")

      val pool = ThreadUtils.newDaemonSingleThreadExecutor("cic-sync-vs-write")
      try {
        val (syncObserver, syncFuture) = runQueryWithObserver(
          name = "sync",
          pool,
          s"ALTER TABLE delta.`$tempPath` ALTER COLUMN ids SYNC IDENTITY")
        unblockUntilPreCommit(syncObserver)
        busyWaitFor(syncObserver.phases.preparePhase.hasEntered, timeout)

        // A concurrent write commits underneath the in-flight SYNC.
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (10), (20)")

        unblockCommit(syncObserver)
        val ex = intercept[Exception] {
          ThreadUtils.awaitResult(syncFuture, 30.seconds)
        }
        assert(causeChain(ex).exists(_.isInstanceOf[java.util.ConcurrentModificationException]),
          s"SYNC must abort when a write commits underneath it; got: $ex")
      } finally {
        pool.shutdownNow()
      }

      val ids = readDeltaTable(tempPath).select("ids")
      assert(ids.count() === ids.distinct().count(),
        "A SYNC/write race must never produce duplicate identity values.")
    }
  }

  private def cicFeatureOptInDdl: String =
    s"ALTER TABLE delta.`$tempPath` SET TBLPROPERTIES " +
      s"('${TableFeatureProtocolUtils.propertyKey(ConcurrentIdentityColumnsTableFeature)}' = " +
      "'supported')"

  test("CIC feature opt-in converts a plain identity table to the service backend") {
    // Conversion is table-level DDL: opting a stock identity table into the CIC feature via
    // ALTER ... SET TBLPROPERTIES mints a sequence per identity column, seeded strictly past
    // the existing data / schema HWM, and stamps the pointer. A subsequent service-backed
    // INSERT continues past the pre-conversion values.
    withTable("target") {
      spark.sql(
        s"""CREATE TABLE target (
           |  ids BIGINT GENERATED ALWAYS AS IDENTITY,
           |  values INT)
           |USING DELTA
           |LOCATION '$tempPath'
           |tblproperties(
           |  ${TableFeatureProtocolUtils.propertyKey(IdentityColumnsTableFeature)} = 'enabled')
           |""".stripMargin)
      // Stock identity writes (no CIC feature, conf off): schema-HWM generation.
      spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (10), (20), (30)")
      val maxBefore = selectMaxId
      assert(syncedSequenceId.isEmpty, "Setup: a stock identity table carries no sequenceId.")

      val numCreatesBefore = localService.createSequenceCount
      spark.sql(cicFeatureOptInDdl)

      assert(localService.createSequenceCount === numCreatesBefore + 1,
        "Conversion must mint exactly one sequence for one identity column.")
      assert(syncedSequenceId.isDefined, "Conversion must stamp the sequence pointer.")
      withSQLConf(DeltaSQLConf.CONCURRENT_IDENTITY_COLUMN_ENABLED.key -> "true") {
        spark.sql(s"INSERT INTO delta.`$tempPath` (values) VALUES (40), (50)")
      }
      assert(selectMaxId > maxBefore,
        s"Post-conversion values must clear the pre-conversion max $maxBefore, got $selectMaxId.")
      assertCorrectIdentityColumn(readDeltaTable(tempPath).select("ids"), expectedSize = 5L)
    }
  }

  test("CIC feature opt-in converts an unconverted feature-on table in place") {
